CREATE TABLE IF NOT EXISTS sys_dictionary_item (
    id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    type_code VARCHAR(100) NOT NULL,
    parent_id BIGINT NOT NULL DEFAULT 0,
    item_label VARCHAR(100) NOT NULL,
    item_value VARCHAR(100) NOT NULL,
    item_tag VARCHAR(100) NULL,
    sort INT NOT NULL DEFAULT 0,
    status TINYINT NOT NULL DEFAULT 0,
    remark VARCHAR(255) NULL,
    create_by VARCHAR(64) NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(64) NULL,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_sys_dictionary_item_tenant_type_value (tenant_id, type_code, item_value),
    KEY idx_sys_dictionary_item_parent (parent_id),
    KEY idx_sys_dictionary_item_status (status),
    KEY idx_sys_dictionary_item_sort (sort)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='System dictionary item';
