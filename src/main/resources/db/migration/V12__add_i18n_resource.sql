CREATE TABLE IF NOT EXISTS sys_i18n_resource (
    id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    locale VARCHAR(32) NOT NULL,
    namespace VARCHAR(64) NOT NULL,
    resource_key VARCHAR(128) NOT NULL,
    resource_value TEXT NOT NULL,
    version INT NOT NULL DEFAULT 1,
    status TINYINT NOT NULL DEFAULT 0,
    remark VARCHAR(255) NULL,
    create_by VARCHAR(64) NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(64) NULL,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_sys_i18n_resource_tenant_locale_key (tenant_id, locale, namespace, resource_key),
    KEY idx_sys_i18n_resource_locale (locale),
    KEY idx_sys_i18n_resource_namespace (namespace),
    KEY idx_sys_i18n_resource_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='I18n resource';
